-- MangaMunchies community features: run once in Supabase SQL Editor. Safe to rerun; does not delete existing manga.
create table if not exists public.manga_view_counts(
  manga_title text primary key,
  views bigint not null default 0 check (views >= 0),
  updated_at timestamptz not null default now()
);
alter table public.manga_view_counts enable row level security;
grant select on public.manga_view_counts to anon, authenticated;
drop policy if exists "Anyone can read manga view counts" on public.manga_view_counts;
create policy "Anyone can read manga view counts" on public.manga_view_counts for select to anon,authenticated using (true);

create or replace function public.increment_manga_view(manga_title_input text)
returns void language plpgsql security definer set search_path=public as $$
begin
  if manga_title_input is null or length(trim(manga_title_input))=0 or length(manga_title_input)>150 then
    raise exception 'Invalid manga title';
  end if;
  insert into public.manga_view_counts(manga_title,views,updated_at)
  values(trim(manga_title_input),1,now())
  on conflict(manga_title) do update set views=public.manga_view_counts.views+1,updated_at=now();
end; $$;
grant execute on function public.increment_manga_view(text) to anon,authenticated;

create table if not exists public.manga_comments(
  id bigint generated by default as identity primary key,
  manga_title text not null,
  display_name text not null check(length(trim(display_name)) between 1 and 40),
  comment text not null check(length(trim(comment)) between 1 and 1000),
  created_at timestamptz not null default now()
);
create index if not exists manga_comments_title_created_idx on public.manga_comments(manga_title,created_at desc);
alter table public.manga_comments enable row level security;
grant select,insert,delete on public.manga_comments to anon,authenticated;
grant usage,select on sequence public.manga_comments_id_seq to anon,authenticated;
drop policy if exists "Anyone can read manga comments" on public.manga_comments;
create policy "Anyone can read manga comments" on public.manga_comments for select to anon,authenticated using(true);
drop policy if exists "Visitors can post manga comments" on public.manga_comments;
create policy "Visitors can post manga comments" on public.manga_comments for insert to anon,authenticated with check(length(trim(manga_title)) between 1 and 150 and length(trim(display_name)) between 1 and 40 and length(trim(comment)) between 1 and 1000);
drop policy if exists "Owner can delete manga comments" on public.manga_comments;
create policy "Owner can delete manga comments" on public.manga_comments for delete to authenticated using(exists(select 1 from public.site_admins where user_id=auth.uid()));
