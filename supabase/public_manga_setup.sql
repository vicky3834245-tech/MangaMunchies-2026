-- MangaMunchies public manga + Owner Dashboard setup
-- Run this in Supabase SQL Editor. It keeps public viewing and public uploads.

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('manga-pages','manga-pages',true,8388608,array['image/jpeg','image/png','image/webp','image/gif'])
on conflict(id) do update set public=true,file_size_limit=8388608,allowed_mime_types=excluded.allowed_mime_types;

create table if not exists public.public_manga(
 id bigint generated by default as identity primary key,
 title text not null,
 volume text not null default '',
 storage_path text not null unique,
 created_at timestamptz not null default now()
);
alter table public.public_manga enable row level security;
drop policy if exists "Anyone can view public manga" on public.public_manga;
create policy "Anyone can view public manga" on public.public_manga for select to anon,authenticated using(true);
drop policy if exists "Anyone can upload manga records" on public.public_manga;
create policy "Anyone can upload manga records" on public.public_manga for insert to anon,authenticated with check(length(title) between 1 and 100 and length(volume)<=100 and storage_path<>'');
drop policy if exists "Anyone can upload manga images" on storage.objects;
create policy "Anyone can upload manga images" on storage.objects for insert to anon,authenticated with check(bucket_id='manga-pages');
drop policy if exists "Anyone can read manga images" on storage.objects;
create policy "Anyone can read manga images" on storage.objects for select to anon,authenticated using(bucket_id='manga-pages');

-- Owner can verify only their own site_admins row. Existing owner UID row is retained.
drop policy if exists "Owner can verify own admin row" on public.site_admins;
create policy "Owner can verify own admin row" on public.site_admins for select to authenticated using(user_id=auth.uid());

-- Only an authenticated site_admin can delete public manga records and files.
drop policy if exists "Owner can delete public manga" on public.public_manga;
create policy "Owner can delete public manga" on public.public_manga for delete to authenticated
using(exists(select 1 from public.site_admins where user_id=auth.uid()));
drop policy if exists "Owner can delete manga page files" on storage.objects;
create policy "Owner can delete manga page files" on storage.objects for delete to authenticated
using(bucket_id='manga-pages' and exists(select 1 from public.site_admins where user_id=auth.uid()));

-- Shared website theme. Everyone can read it; only the site owner can change it.
create table if not exists public.site_settings(
 setting_key text primary key,
 setting_value text not null
);
alter table public.site_settings enable row level security;
insert into public.site_settings(setting_key,setting_value) values('theme','midnight') on conflict(setting_key) do nothing;
drop policy if exists "Anyone can read site settings" on public.site_settings;
create policy "Anyone can read site settings" on public.site_settings for select to anon,authenticated using(true);
drop policy if exists "Owner can insert site settings" on public.site_settings;
create policy "Owner can insert site settings" on public.site_settings for insert to authenticated
with check(exists(select 1 from public.site_admins where user_id=auth.uid()));
drop policy if exists "Owner can update site settings" on public.site_settings;
create policy "Owner can update site settings" on public.site_settings for update to authenticated
using(exists(select 1 from public.site_admins where user_id=auth.uid()))
with check(exists(select 1 from public.site_admins where user_id=auth.uid()));
